function ensureDirectoryExists(dirPath) {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true })
    console.log(`Directory created: ${dirPath}`)
  }
}

function fetchUserPosts(mode, identifier) {
  switch (mode) {
    case "username":
      console.log(`Selected username: ${identifier}`)
      axios.get(`https://vine.co/api/users/profiles/vanity/${identifier}`).then(resp => {
        console.log(`User Id Found! ${resp.data.data.userIdStr}`)
        fetchPosts(resp.data.data.userIdStr, identifier)
      })
      break;
    case "userid":
      console.log(`Selected userid: ${identifier}`)
      fetchPosts(identifier)
      break;
  }
}

function fetchPosts(userid, username = null) {
  axios.get(`https://archive.vine.co/profiles/${userid}.json`).then(resp => {
    console.log(`${resp.data.posts.length} post from ${(username != null) ? username : userid} has been found. Starting to download videos.`)
    downloadPost(resp.data.posts, 0, (username != null) ? username : userid)
  })
}

function downloadPost(parr, pin, username) {
  performance.mark("A")
  axios.get(`https://archive.vine.co/posts/${parr[pin]}.json`).then((resp) => {
    ensureDirectoryExists(path.resolve(process.cwd() + `\\videos\\${username}`))
    let proc = cprocess.exec(`ffmpeg -i ${resp.data.videoUrl} "${path.resolve(process.cwd() + `\\videos\\${username}\\${resp.data.postIdStr}.mp4" -y`)}"`)
    proc.on("exit", () => {
      performance.mark("B")
      console.log(`${resp.data.postIdStr} downloaded. It took ${performance.measure("", "A", "B").duration.toFixed(0)}ms to download.`)
      downloadPost(parr, pin + 1, username)
    })
  }).catch(() => {
    console.log(`${parr[pin]} not found, skipping...`)
    if (pin + 1 >= parr.length) {
      console.log("Download complete!")
      return
    }
    downloadPost(parr, pin + 1, username)
  })
}


